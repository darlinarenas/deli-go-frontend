async function getOrdersByRestaurant(email) {
  const normalizedEmail = normalizeText(email);

  try {
    const response = await fetch(
      `${DELI_ORDERS_API_URL}/orders/restaurant/${encodeURIComponent(normalizedEmail)}`
    );

    const data = await response.json();

    if (response.ok && data.ok) {
      const normalizedOrders = normalizeOrdersList(data.orders);

      // CAMBIO BHUZ RESTAURANTE LIVE:
      // Cuando el panel restaurante refresca pedidos desde backend,
      // se detectan pedidos nuevos después de la primera carga y se muestra:
      // - sonido propio del restaurante
      // - popup/tarjeta breve
      // - vibración compatible
      // - glow visual en la tarjeta del pedido
      if (
        window.BHUZ_LIVE_NOTIFICATIONS &&
        typeof window.BHUZ_LIVE_NOTIFICATIONS.processRestaurantOrders === "function"
      ) {
        window.BHUZ_LIVE_NOTIFICATIONS.processRestaurantOrders(normalizedOrders);
      }

      return normalizedOrders;
    }
  } catch (error) {
    console.warn("No se pudo leer pedidos del restaurante desde backend:", error);
  }

  // CAMBIO: conectar frontend con backend Render - no usar backend como fuente principal si falla el backend
  return [];
}

