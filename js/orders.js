  function safeCssEscape(value) {
    if (window.CSS && typeof window.CSS.escape === "function") {
      return window.CSS.escape(value);
    }

    return String(value).replace(/[^a-zA-Z0-9_-]/g, "\\$&");
  }

  function glowOrderCard(orderId) {
    const safeId = String(orderId || "");
    if (!safeId) return;

    const escapedId = safeCssEscape(safeId);

    const selectors = [
      `[data-order-id="${escapedId}"]`,
      `.order-card[data-id="${escapedId}"]`,
      `.order-card[data-order="${escapedId}"]`
    ];

    const card = document.querySelector(selectors.join(","));
    if (!card) return;

    card.classList.remove("updated-glow", "bhuz-live-card-updated");
    void card.offsetWidth;
    card.classList.add("updated-glow", "bhuz-live-card-updated");

    setTimeout(() => {
      card.classList.remove("bhuz-live-card-updated");
    }, 2400);
  }

  function showToast(order, previousStatus, nextStatus) {
    if (typeof document === "undefined" || !document.body) return;

    const normalizedStatus = normalizeOrderStatus(nextStatus);
    const copy = getNotificationCopy(normalizedStatus);
    const root = ensureRoot();

    const toast = document.createElement("div");
    toast.className = `bhuz-live-toast bhuz-live-${normalizedStatus}`;
    toast.innerHTML = `
      <div class="bhuz-live-icon">${getStatusIcon(normalizedStatus)}</div>
      <div class="bhuz-live-content">
        <strong>${escapeLiveHtml(copy.title)}</strong>
        <span>${escapeLiveHtml(copy.message)}</span>
        <small>${escapeLiveHtml(order.restaurantName || "BHUZ")}</small>
      </div>
      <button class="bhuz-live-close" type="button" aria-label="Cerrar notificación">×</button>
    `;

    root.appendChild(toast);

    const closeBtn = toast.querySelector(".bhuz-live-close");
    if (closeBtn) {
      closeBtn.addEventListener("click", () => removeToast(toast));
    }

    setTimeout(() => removeToast(toast), 6500);
    playStatusSound(normalizedStatus);

    // CAMBIO BHUZ LIVE GLOBAL:
    // Vibración real en móviles compatibles, sin afectar desktop.
    if (navigator.vibrate) {
      navigator.vibrate([80, 40, 80]);
    }

    glowOrderCard(order.id);

    window.dispatchEvent(new CustomEvent("bhuz:order-status-changed", {
      detail: {
        order,
        previousStatus,
        nextStatus: normalizedStatus
      }
    }));
  }

  function removeToast(toast) {
    if (!toast || toast.classList.contains("is-hiding")) return;

    toast.classList.add("is-hiding");
    setTimeout(() => {
      const parentRoot = toast.parentNode;

      if (toast.parentNode) {
        toast.parentNode.removeChild(toast);
      }

      // CAMBIO BHUZ RESTAURANTE LIVE:
      // Si ya no quedan notificaciones, se elimina el root completo para que
      // la pantalla vuelva a quedar 100% manipulable y sin blur encima.
      const liveRoot = parentRoot || document.getElementById("bhuzLiveRoot");
      if (liveRoot && liveRoot.children && liveRoot.children.length === 0 && liveRoot.parentNode) {
        liveRoot.parentNode.removeChild(liveRoot);
      }
    }, 260);
  }

  function getStatusIcon(status) {
    switch (normalizeOrderStatus(status)) {
      case "aceptado":
        return "✅";
      case "preparando":
        return "👨‍🍳";
      case "listo":
        return "🔥";
      case "en_camino":
        return "🛵";
      case "entregado":
        return "🎉";
      default:
        return "🔔";
    }
  }

  function escapeLiveHtml(text) {
    return String(text || "")
      .replaceAll("&", "&amp;")
      .replaceAll("<", "&lt;")
      .replaceAll(">", "&gt;")
      .replaceAll('"', "&quot;")
      .replaceAll("'", "&#039;");
  }

  // CAMBIO BHUZ RESTAURANTE LIVE:
  // Genera el detalle tipo boleta/factura para el popup del restaurante.
  // Mantiene la información real del pedido y NO muestra costo de delivery.
  function getRestaurantOrderReceiptHtml(order) {
    const items = Array.isArray(order?.items) ? order.items : [];

    if (!items.length) {
      return `
        <div class="bhuz-restaurant-receipt-empty">
          Pedido nuevo sin detalle de productos.
        </div>
      `;
    }

    return items.map((item) => {
      const qty = Number(item?.qty || 1);
      const name = item?.name || "Producto";
      const price = Number(item?.price || 0);
      const subtotal = Number(
        item?.subtotal != null
          ? item.subtotal
          : qty * price
      );

      return `
        <div class="bhuz-restaurant-boleta-row">
          <span class="bhuz-restaurant-boleta-product">${escapeLiveHtml(qty)}x ${escapeLiveHtml(name)}</span>
          <span class="bhuz-restaurant-boleta-qty">${escapeLiveHtml(qty)}</span>
          <span class="bhuz-restaurant-boleta-price">${escapeLiveHtml(formatPrice(price))}</span>
          <strong class="bhuz-restaurant-boleta-subtotal">${escapeLiveHtml(formatPrice(subtotal))}</strong>
        </div>
      `;
    }).join("");
  }

  function getRestaurantOrderDateLabel(order) {
    try {
      const baseDate = order?.createdAt ? new Date(order.createdAt) : new Date();

      if (Number.isNaN(baseDate.getTime())) {
        return order?.date || "Hoy";
      }

      return baseDate.toLocaleDateString("es-CL", {
        day: "2-digit",
        month: "long",
        year: "numeric"
      });
    } catch (error) {
      return order?.date || "Hoy";
    }
  }

  // CAMBIO BHUZ RESTAURANTE LIVE:
