/* ======================================================
   BLOQUE 6
   NORMALIZAR ESTRUCTURA DE PEDIDO
====================================================== */
function normalizeOrder(order) {
  if (!order || typeof order !== "object") return null;

  const restaurantObject =
    order.restaurant && typeof order.restaurant === "object"
      ? order.restaurant
      : {};

  const customerObject =
    order.customer && typeof order.customer === "object"
      ? order.customer
      : {};

  const items = Array.isArray(order.items)
    ? order.items.map((item) => {
        const qty = Number(item?.qty || 0);
        const price = Number(item?.price || 0);

        return {
          id: item?.id || "",
          name: item?.name || "Producto",
          qty,
          price,
          subtotal: Number(
            item?.subtotal != null ? item.subtotal : qty * price
          )
        };
      })
    : [];

  const latitude = String(
    order.latitude ||
    order.location?.lat ||
    customerObject.location?.lat ||
    customerObject.latitude ||
    ""
  ).trim();

  const longitude = String(
    order.longitude ||
    order.location?.lng ||
    customerObject.location?.lng ||
    customerObject.longitude ||
    ""
  ).trim();

  const deliveryReference =
    order.deliveryReference ||
    customerObject.reference ||
    order.reference ||
    "";

  const deliveryAddress =
    order.deliveryAddress ||
    customerObject.address ||
    order.address ||
    "";

  return {
    id: order.id || `order_${Date.now()}`,
    restaurantEmail: normalizeText(
      order.restaurantEmail || restaurantObject.email || ""
    ),
    restaurantName:
      order.restaurantName || restaurantObject.name || "Restaurante",
    restaurant: {
      email: normalizeText(
        restaurantObject.email || order.restaurantEmail || ""
      ),
      name: restaurantObject.name || order.restaurantName || "Restaurante",
      id: restaurantObject.id || order.restaurantId || ""
    },
    items,
    total: Number(order.total || 0),
    customer: {
      fullName:
        customerObject.fullName ||
        customerObject.name ||
        order.fullName ||
        "",
      phone:
        customerObject.phone ||
        order.phone ||
        "",
      address: deliveryAddress,
      email:
        customerObject.email ||
        order.email ||
        "",
      reference: deliveryReference,
      location: {
        lat: latitude,
        lng: longitude
      }
    },
    deliveryAddress,
    deliveryReference,
    latitude,
    longitude,
    location: {
      lat: latitude,
      lng: longitude
    },
    status: normalizeOrderStatus(order.status),
    deliveryCode: String(order.deliveryCode || order.delivery_code || "").trim(),
    deliveryCodeUsed:
      order.deliveryCodeUsed === true ||
      order.delivery_code_used === true ||
      String(order.deliveryCodeUsed ?? order.delivery_code_used ?? "").toLowerCase() === "true",
    paymentMethod: order.paymentMethod || "pendiente",
    notes: order.notes || "",
    date: order.date || "",
    time: order.time || "",
    createdAt: order.createdAt || new Date().toISOString()
  };
}

function normalizeOrdersList(list) {
  if (!Array.isArray(list)) return [];
  return list.map(normalizeOrder).filter(Boolean);
}

